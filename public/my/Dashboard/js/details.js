// ============================================================
// FILTER STATE
// ============================================================

let currentColumn = null;

// Stores selected filters for each column
const filters = {};


// ============================================================
// SORT STATE
// ============================================================

const sortState = {
  column: null,
  order: null, // "asc" or "desc"
};


// ============================================================
// PAGINATION STATE
// ============================================================

let currentPage = 1;

// Default rows per page
let rowsPerPage = 25;


// ============================================================
// GET GROUP
// ============================================================

const params = new URLSearchParams(window.location.search);
const group = params.get("group");


if (group && tableData[group]) {

  document.getElementById("tableTitle").innerText =
    tableTitles[group];

  loadOnlineStatus();
}


// ============================================================
// RENDER TABLE
// ============================================================

function renderTable() {

  tbody.innerHTML = "";

  let data = [...tableData[group]];


  // ==========================================================
  // APPLY FILTERS
  // ==========================================================

  Object.keys(filters).forEach((column) => {

    data = data.filter((person) => {

      let value;

      if (column === "status") {

        value = person.status
          ? "Online"
          : "Offline";

      } else {

        value = person[column];

      }

      return filters[column].includes(value);

    });

  });


  // ==========================================================
  // APPLY SORTING
  // ==========================================================

  if (sortState.column) {

    data.sort((a, b) => {

      let valueA =
        sortState.column === "status"
          ? a.status
            ? "Online"
            : "Offline"
          : a[sortState.column];

      let valueB =
        sortState.column === "status"
          ? b.status
            ? "Online"
            : "Offline"
          : b[sortState.column];


      // Prevent null / undefined errors
      valueA = valueA ?? "";
      valueB = valueB ?? "";


      const result = valueA
        .toString()
        .localeCompare(
          valueB.toString(),
          undefined,
          {
            numeric: true,
            sensitivity: "base"
          }
        );


      return sortState.order === "asc"
        ? result
        : -result;

    });

  }


  // ==========================================================
  // RECORD COUNT
  // ==========================================================

  const totalRecords = tableData[group].length;
  const filteredRecords = data.length;

  const hasFilters =
    Object.keys(filters).length > 0;


  const clearAllBtn =
    document.getElementById("clearAllFilters");


  clearAllBtn.style.display =
    hasFilters
      ? "inline-block"
      : "none";


  document.getElementById("recordCount").textContent =
    hasFilters
      ? `Showing ${filteredRecords} of ${totalRecords} records`
      : `Total Records: ${totalRecords}`;


  // ==========================================================
  // PAGINATION CALCULATION
  // ==========================================================

 const totalPages = Math.ceil(data.length / rowsPerPage);

const paginationContainer =
  document.querySelector(".pagination-container");

if (data.length <= 25) {

  // 25 or fewer records:
  // hide Rows per page + pagination
  paginationContainer.style.display = "none";

} else {

  // More than 25 records:
  // show Rows per page + pagination
  paginationContainer.style.display = "flex";

  renderPagination(totalPages);
}


  // ==========================================================
  // GET ONLY CURRENT PAGE DATA
  // ==========================================================

  const startIndex =
    (currentPage - 1) * rowsPerPage;

  const endIndex =
    startIndex + rowsPerPage;


  const pageData =
    data.slice(startIndex, endIndex);


  // ==========================================================
  // RENDER CURRENT PAGE
  // ==========================================================

  pageData.forEach((person) => {

    tbody.innerHTML += `
      <tr>

        <td>${person.name}</td>

        <td>${person.designation}</td>

        <td>${person.department}</td>

        <td>${person.branch}</td>

        <td>
          <span class="status ${
            person.status
              ? "online"
              : "offline"
          }"></span>
        </td>

        <td>${person.lastAccess || ""}</td>

      </tr>
    `;

  });


  // ==========================================================
  // RENDER PAGINATION
  // ==========================================================

  renderPagination(totalPages);

}


// ============================================================
// GET FILTERED DATA
// ============================================================

function getFilteredData(excludeColumn = null) {

  let data = [...tableData[group]];


  Object.keys(filters).forEach((column) => {

    // Ignore current column
    if (column === excludeColumn) {
      return;
    }


    data = data.filter((person) => {

      const value =
        column === "status"
          ? person.status
            ? "Online"
            : "Offline"
          : person[column];


      return filters[column].includes(value);

    });

  });


  return data;
}


// ============================================================
// FILTER MENU
// ============================================================

function openFilterMenu(th) {

  // Position popup
  const rect = th.getBoundingClientRect();


  filterMenu.style.left =
    rect.left +
    window.scrollX +
    "px";


  filterMenu.style.top =
    rect.bottom +
    window.scrollY +
    "px";


  // ==========================================================
  // GET UNIQUE VALUES
  // ==========================================================

  const values = [

    ...new Set(

      getFilteredData(currentColumn).map(
        (person) => {

          if (currentColumn === "status") {

            return person.status
              ? "Online"
              : "Offline";

          }

          return person[currentColumn];

        }
      )

    )

  ]
    .filter(
      (value) =>
        value !== undefined &&
        value !== null
    )
    .sort((a, b) =>
      a
        .toString()
        .localeCompare(
          b.toString(),
          undefined,
          {
            numeric: true,
            sensitivity: "base"
          }
        )
    );


  // ==========================================================
  // SELECT ALL STATE
  // ==========================================================

  const allSelected =
    !filters[currentColumn] ||
    values.every((value) =>
      filters[currentColumn].includes(value)
    );


  // ==========================================================
  // CREATE FILTER POPUP
  // ==========================================================

  filterMenu.innerHTML = `

    <button id="sortAsc">
      Sort A → Z
    </button>

    <button id="sortDesc">
      Sort Z → A
    </button>

    <hr>

    <input
      type="text"
      id="filterSearch"
      placeholder="Search..."
    >

    <div class="filter-values">

      <label>

        <input
          type="checkbox"
          id="selectAll"
          ${allSelected ? "checked" : ""}
        >

        <strong>Select All</strong>

      </label>

      <hr>

      ${values
        .map((value) => {

          const checked =
            !filters[currentColumn] ||
            filters[currentColumn].includes(value);


          return `

            <label class="filter-item">

              <input
                type="checkbox"
                value="${value}"
                ${checked ? "checked" : ""}
              >

              ${value}

            </label>

          `;

        })
        .join("")}

    </div>


    <button id="applyFilter">
      Apply
    </button>

    <button id="clearFilter">
      Clear
    </button>

  `;


  // ==========================================================
  // SEARCH INSIDE FILTER
  // ==========================================================

  const filterSearch =
    document.getElementById("filterSearch");


  filterSearch.addEventListener(
    "input",
    () => {

      const search =
        filterSearch.value.toLowerCase();


      filterMenu
        .querySelectorAll(".filter-item")
        .forEach((item) => {

          const text =
            item.textContent.toLowerCase();


          item.style.display =
            text.includes(search)
              ? "block"
              : "none";

        });

    }
  );


  // ==========================================================
  // SORT ASCENDING
  // ==========================================================

  document
    .getElementById("sortAsc")
    .addEventListener(
      "click",
      () => {

        sortState.column =
          currentColumn;

        sortState.order =
          "asc";


        // Go back to first page
        currentPage = 1;


        filterMenu.classList.add(
          "hidden"
        );


        renderTable();

      }
    );


  // ==========================================================
  // SORT DESCENDING
  // ==========================================================

  document
    .getElementById("sortDesc")
    .addEventListener(
      "click",
      () => {

        sortState.column =
          currentColumn;

        sortState.order =
          "desc";


        // Go back to first page
        currentPage = 1;


        filterMenu.classList.add(
          "hidden"
        );


        renderTable();

      }
    );


  filterMenu.classList.remove(
    "hidden"
  );


  // ==========================================================
  // APPLY FILTER
  // ==========================================================

  document
    .getElementById("applyFilter")
    .addEventListener(
      "click",
      () => {

        const checkedValues =
          Array.from(
            filterMenu.querySelectorAll(
              ".filter-item"
            )
          )
            .filter(
              (item) =>
                item.style.display !==
                "none"
            )
            .map(
              (item) =>
                item.querySelector(
                  "input"
                )
            )
            .filter(
              (input) =>
                input.checked
            )
            .map(
              (input) =>
                input.value
            );


        filters[currentColumn] =
          checkedValues;


        // Go to first page after filtering
        currentPage = 1;


        filterMenu.classList.add(
          "hidden"
        );


        renderTable();

      }
    );


  // ==========================================================
  // CLEAR CURRENT FILTER
  // ==========================================================

  document
    .getElementById("clearFilter")
    .addEventListener(
      "click",
      () => {

        delete filters[
          currentColumn
        ];


        currentPage = 1;


        filterMenu.classList.add(
          "hidden"
        );


        renderTable();

      }
    );


  // ==========================================================
  // SELECT ALL
  // ==========================================================

  document
    .getElementById("selectAll")
    .addEventListener(
      "change",
      function () {

        const checked =
          this.checked;


        filterMenu
          .querySelectorAll(
            ".filter-item input"
          )
          .forEach(
            (cb) =>
              (cb.checked = checked)
          );

      }
    );

}


// ============================================================
// PAGINATION
// ============================================================

function renderPagination(totalPages) {

  const pagination =
    document.getElementById(
      "pagination"
    );


  if (!pagination) {
    return;
  }


  pagination.innerHTML = "";


  // No pagination required
  if (totalPages <= 1) {
    return;
  }


  // ==========================================================
  // PREVIOUS BUTTON
  // ==========================================================

  const previousButton =
    document.createElement("button");


  previousButton.textContent = "‹";

  previousButton.disabled =
    currentPage === 1;


  previousButton.addEventListener(
    "click",
    () => {

      if (currentPage > 1) {

        currentPage--;

        renderTable();

      }

    }
  );


  pagination.appendChild(
    previousButton
  );


  // ==========================================================
  // PAGE BUTTON HELPER
  // ==========================================================

  function addPageButton(page) {

    const button =
      document.createElement(
        "button"
      );


    button.textContent = page;


    if (page === currentPage) {

      button.classList.add(
        "active"
      );

    }


    button.addEventListener(
      "click",
      () => {

        currentPage = page;

        renderTable();

      }
    );


    pagination.appendChild(
      button
    );

  }


  // ==========================================================
  // ELLIPSIS
  // ==========================================================

  function addEllipsis() {

    const span =
      document.createElement(
        "span"
      );


    span.textContent = "…";

    span.className =
      "pagination-ellipsis";


    pagination.appendChild(
      span
    );

  }


  // ==========================================================
  // PAGE NUMBER LOGIC
  //
  // Example:
  //
  // 1 2 3 4 5 ... 28 29 30
  //
  // When on page 15:
  //
  // 1 ... 13 14 15 16 17 ... 30
  // ==========================================================

  const maxVisiblePages = 7;


  if (totalPages <= maxVisiblePages) {

    // Show every page
    for (
      let page = 1;
      page <= totalPages;
      page++
    ) {

      addPageButton(page);

    }

  } else {

    // --------------------------------------------------------
    // Always show first page
    // --------------------------------------------------------

    addPageButton(1);


    // --------------------------------------------------------
    // Current page near beginning
    // --------------------------------------------------------

    if (currentPage <= 4) {

      for (
        let page = 2;
        page <= 5;
        page++
      ) {

        addPageButton(page);

      }


      addEllipsis();


      addPageButton(totalPages);

    }


    // --------------------------------------------------------
    // Current page in middle
    // --------------------------------------------------------

    else if (
      currentPage >= 5 &&
      currentPage <= totalPages - 4
    ) {

      addEllipsis();


      addPageButton(
        currentPage - 1
      );

      addPageButton(
        currentPage
      );

      addPageButton(
        currentPage + 1
      );


      addEllipsis();


      addPageButton(
        totalPages
      );

    }


    // --------------------------------------------------------
    // Current page near end
    // --------------------------------------------------------

    else {

      addEllipsis();


      for (
        let page =
          totalPages - 4;
        page <= totalPages;
        page++
      ) {

        addPageButton(page);

      }

    }

  }


  // ==========================================================
  // NEXT BUTTON
  // ==========================================================

  const nextButton =
    document.createElement(
      "button"
    );


  nextButton.textContent = "›";


  nextButton.disabled =
    currentPage === totalPages;


  nextButton.addEventListener(
    "click",
    () => {

      if (
        currentPage <
        totalPages
      ) {

        currentPage++;

        renderTable();

      }

    }
  );


  pagination.appendChild(
    nextButton
  );

}


